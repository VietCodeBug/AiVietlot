import { chromium } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { loadEnv } from 'vite'

const base = process.argv[2] ?? process.env.QA_BASE_URL ?? 'http://127.0.0.1:4173'
const env = loadEnv('production', process.cwd(), 'VITE_')
const response = await fetch(`${env.VITE_SUPABASE_URL}/rest/v1/mega645_draws?select=draw_id&order=draw_id.desc&limit=1`, { headers: { apikey: env.VITE_SUPABASE_PUBLISHABLE_KEY } })
if (!response.ok) throw new Error('Cannot verify live source for browser QA')
const latest = (await response.json())[0].draw_id
const output = new URL('../../artifacts/web-qa/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const checks = [], errors = []
const check = (ok, name) => { if (!ok) throw new Error(name); checks.push(name) }
const contexts = []
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
  contexts.push(context)
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base)
  await page.locator('.latest-title').waitFor({ timeout: 30000 })
  await page.evaluate(() => document.fonts.ready)
  check((await page.locator('.latest-title').innerText()).includes(`#${String(latest).padStart(5, '0')}`), 'Overview shows actual newest database draw')
  await page.screenshot({ path: new URL('desktop-overview.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true })
  for (const route of ['/thong-ke', '/thi-nghiem', '/kiem-thu', '/cai-dat', '/lich-su']) {
    await page.goto(base + route)
    await page.locator('h1').waitFor()
    await page.waitForTimeout(500)
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Desktop route ${route} has no page overflow and reloads`)
  }
  await page.locator('.history-row').first().waitFor({ timeout: 20000 })
  const first = await page.locator('.history-date strong').first().innerText()
  await page.getByRole('button', { name: 'Trang sau' }).click()
  await page.waitForFunction(previous => document.querySelector('.history-date strong')?.textContent !== previous, first)
  check((await page.locator('.history-date strong').first().innerText()) !== first, 'Database history pagination changes rows')
  await page.getByLabel('Số xuất hiện').selectOption('7')
  await page.waitForTimeout(1200)
  check((await page.locator('.history-row').count()) > 0, 'History supports number filter')
  const ballRows = await page.locator('.history-row .balls').allTextContents()
  check(ballRows.every(text => text.includes('07')), 'Number filter returns matching actual draws')
  await page.goto(base + '/thong-ke')
  await page.locator('.heat-cell').first().waitFor()
  await page.getByRole('button', { name: '30 kỳ', exact: true }).click()
  check((await page.locator('.scope-bar').innerText()).includes('30 mẫu'), 'Statistics switches to exactly 30 input draws')
  check(await page.locator('.heat-cell').count() === 45, 'Statistics shows all 45 numbers')
  await page.locator('.heat-cell').nth(16).click()
  check((await page.locator('.detail-ball').innerText()) === '17', 'Tap selects number details')
  await page.screenshot({ path: new URL('desktop-statistics.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true })
  await page.goto(base + '/thi-nghiem')
  await page.getByRole('button', { name: 'Tạo dãy thí nghiệm' }).click()
  await page.locator('.generated-list').waitFor()
  const originalTickets = await page.locator('.generated-list .balls').allTextContents()
  check(originalTickets.length === 5 && new Set(originalTickets).size === 5, 'Generator creates five distinct valid tickets')
  await page.getByRole('button', { name: 'Tạo dãy thí nghiệm' }).click()
  check(JSON.stringify(originalTickets) === JSON.stringify(await page.locator('.generated-list .balls').allTextContents()), 'Same generator seed reproduces tickets')
  await page.getByRole('button', { name: 'Lưu thí nghiệm' }).click()
  await page.locator('.notebook-entry').waitFor()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('mega-lab-notebook'))[0])
  check(/^[a-f0-9]{64}$/.test(saved.inputHash) && saved.lastDraw === latest && saved.inputCount === 100 && saved.halfLife === 30 && saved.smoothing === 1, 'Notebook preserves the generation input hash, range and full configuration')
  await page.reload()
  await page.locator('.notebook-entry').waitFor()
  check(await page.locator('.notebook-entry').count() > 0, 'Notebook survives reload and stays labelled as device storage')
  await page.getByLabel('Sáu số của bạn').fill('01 09 17 25 33 45')
  await page.getByRole('button', { name: /Đối chiếu .* kỳ/ }).click()
  await page.locator('.manual-result').waitFor()
  check(await page.locator('.match-histogram>div').count() === 7, 'Manual historical comparison includes all 0–6 match counts')
  await page.screenshot({ path: new URL('desktop-experiments.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true })
  await page.goto(base + '/kiem-thu')
  await page.locator('.comparison-card').first().waitFor({ timeout: 20000 })
  check(await page.locator('.comparison-card').count() === 3, 'Backtest reads all three actual server analysis comparisons')
  await page.screenshot({ path: new URL('desktop-backtests.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true })
  await page.goto(base + '/cai-dat')
  await page.locator('.theme-options button').nth(1).click()
  check(await page.evaluate(() => document.documentElement.dataset.theme === 'dark'), 'Dark theme applies')
  await page.reload()
  check(await page.evaluate(() => document.documentElement.dataset.theme === 'dark'), 'Theme survives reload')
  await page.locator('.theme-options button').first().click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Xuất CSV', exact: true }).click()
  check((await download).suggestedFilename().endsWith('.csv'), 'CSV export produces a downloadable file')
  await page.goto(base)
  await page.locator('.latest-title').waitFor()
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await page.locator('.latest-title').waitFor()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await context.setOffline(true)
  await page.reload()
  await page.locator('.latest-title').waitFor()
  check((await page.locator('.banner').first().innerText()).includes('ngoại tuyến'), 'PWA reloads offline with an explicit cached-data state')
  await context.setOffline(false)
  for (const width of [390, 360]) {
    const mobile = await browser.newContext({ viewport: { width, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
    contexts.push(mobile)
    const phone = await mobile.newPage()
    phone.on('pageerror', error => errors.push(error.message))
    for (const route of ['/', '/thong-ke', '/thi-nghiem', '/kiem-thu', '/cai-dat', '/lich-su']) {
      await phone.goto(base + route)
      await phone.locator('h1').waitFor({ timeout: 20000 })
      if (route === '/') await phone.locator('.latest-title').waitFor({ timeout: 20000 })
      await phone.waitForTimeout(300)
      check(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px mobile route ${route} has no page overflow`)
      if (width === 390 && ['/', '/thong-ke', '/thi-nghiem'].includes(route)) await phone.screenshot({ path: new URL(`mobile-${route === '/' ? 'overview' : route.slice(1)}.png`, output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true })
    }
    await phone.locator('.bottom-nav a[href="/thong-ke"]').click()
    check(phone.url().endsWith('/thong-ke'), `${width}px bottom navigation works by touch`)
    const navBoxes = await phone.locator('.bottom-nav a').evaluateAll(nodes => nodes.map(n => ({width:n.getBoundingClientRect().width,height:n.getBoundingClientRect().height})))
    check(navBoxes.every(n => n.width >= 44 && n.height >= 44), `${width}px main touch targets are at least 44px`)
  }
  check(errors.length === 0, 'No uncaught browser errors')
  const report = { status: 'passed', base, newestDrawVerified: latest, checks, browserErrors: errors, checkedAt: new Date().toISOString() }
  await writeFile(new URL('report.json', output), JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally { for (const context of contexts) await context.close(); await browser.close() }
